/**
 * Turn the browser version of the model into JavaScript.
 *
 * Input:  build/model.nlogox (made by prepare-model.py)
 * Output: runtime/model.js          the compiled model
 *         runtime/reporters.js      read-only questions the page asks the model
 *         runtime/network-*.json    road maps the page shows while the model loads
 *
 * Uses the NetLogo Web compiler saved in build/vendor, so no internet
 * connection is needed. Run it with:  npm run model:web
 */

import fs from "node:fs";
import path from "node:path";
import vm from "node:vm";
import { fileURLToPath } from "node:url";
import { loadTrafficSim, RUNTIME_FOLDER } from "../src/loadInNode";
import type { NetworkName } from "../src/settings";

interface CompileResult {
  success: boolean;
  result: string;
}

interface NetLogoCompiler {
  fromNlogoXML(xml: string): { model: CompileResult };
  compileReporter(expression: string): CompileResult;
}

const buildFolder = path.dirname(fileURLToPath(import.meta.url));

// The compiler script defines a global class called BrowserCompiler.
vm.runInThisContext(fs.readFileSync(path.join(buildFolder, "vendor", "tortoise-compiler.js"), "utf8"));
const BrowserCompiler = vm.runInThisContext("BrowserCompiler") as new () => NetLogoCompiler;
const compiler = new BrowserCompiler();

const result = compiler.fromNlogoXML(fs.readFileSync(path.join(buildFolder, "model.nlogox"), "utf8"));
if (!result.model.success) {
  throw new Error(JSON.stringify(result.model.result));
}
fs.mkdirSync(RUNTIME_FOLDER, { recursive: true });
fs.writeFileSync(path.join(RUNTIME_FOLDER, "model.js"), result.model.result);

// Rates use the same formula as export-link-results in the desktop model.
const hours = "(max list (1 / 3600) (measured-seconds / 3600))";

/** Everything the page reads from the model, written in NetLogo. */
const questions: Record<string, string> = {
  // The numbers shown under the map, plus the selection and baseline state.
  metrics:
    "(list ticks count cars generated-total completed-total stranded-count queued-at-gates mean-trip-time-min mean-delay-min measured-seconds trips-done vehicle-hours run-finished? closure-desc selection-label measuring? (is-list? baseline-signature) (baseline-signature = scenario-signature) baseline-summary selected-street selected-block warm-up-s measure-s)",
  // Position, direction and colour of every car.
  cars: "[ (list who xcor ycor heading color) ] of cars",
  // The road layout. It only changes when Setup runs.
  roads:
    "map [L -> [(list [who] of end1 [who] of end2 street seg geometry lanes road-kind direction-name cars-allowed?)] of L] sort roads",
  // How each road should look right now: colour, width, closures and counts.
  styles:
    "map [L -> [(list color thickness closed? lanes-open win-count base-count tt-ema (closed? or (partner != nobody and [closed?] of partner)) (lanes-open < lanes or (partner != nobody and [lanes-open < lanes] of partner)))] of L] sort roads",
  // Entry gates and destinations.
  nodes: '[ (list xcor ycor node-kind label) ] of nodes with [node-kind != "grid"]',
  // Street name labels.
  labels: "[ (list xcor ycor label) ] of map-labels",
  bounds: "(list min-pxcor max-pxcor min-pycor max-pycor)",
  // One CSV row per drivable road, exactly as the desktop export writes it.
  csv: `map [L -> [(word "\\"" street "\\"," direction-name "," seg ",\\"" node-name end1 "\\",\\"" node-name end2 "\\"," lanes "," lanes-open "," closed? "," precision (win-count / ${hours}) 1 "," precision base-count 1 "," precision ((win-count / ${hours}) - base-count) 1 "," precision tt-ema 1)] of L] filter [L -> [cars-allowed? and road-kind != "access"] of L] sort roads`,
  // The saved baseline, so the browser can store it and bring it back after a reload.
  baseline:
    "(list (ifelse-value is-list? baseline-signature [table:to-list baseline] [[]]) baseline-summary baseline-signature)",
  // Every car is accounted for: finished, stranded, driving or waiting.
  conservation: "generated-total = completed-total + stranded-count + count cars + queued-at-gates",
};

const compiled: string[] = [];
Object.entries(questions).forEach(function (entry) {
  const output = compiler.compileReporter(entry[1]);
  if (!output.success) {
    throw new Error(entry[0] + ": " + JSON.stringify(output));
  }
  compiled.push(
    "  " + JSON.stringify(entry[0]) + ": function () {\n    return (" + output.result + ");\n  }",
  );
});
fs.writeFileSync(
  path.join(RUNTIME_FOLDER, "reporters.js"),
  "// Generated by packages/simulation/build/compile-model.ts. Do not edit.\nself.TRAFFIC_REPORTERS = {\n" +
    compiled.join(",\n") +
    "\n};\n",
);
console.log("Compiled the model and the web reporters.");

// Save both road maps so the page can draw streets while the model starts.
const maps: [string, NetworkName][] = [
  ["osm", "Real OSM map"],
  ["schematic", "Schematic Hoddle grid"],
];
maps.forEach(function (entry) {
  const simulation = loadTrafficSim();
  simulation.set("network-source", entry[1]);
  const world = simulation.setup();
  fs.writeFileSync(path.join(RUNTIME_FOLDER, "network-" + entry[0] + ".json"), JSON.stringify(world));
});
console.log("Saved both road maps.");
